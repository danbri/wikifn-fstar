#!/usr/bin/env node
// Write every generated composition to docs/generated/wikifn.scm, rendered by
// Wikifn.Print.
//
// This runs after the engine is built rather than during generation, because
// the printer is part of the engine. That ordering is the point: there is one
// renderer, it is checked F*, and a printed body cannot disagree with the body
// that runs.
//
//   node scripts/export-all-scheme.js

import { createRequire } from "node:module";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const catalog = require(path.join(root, "docs", "generated", "functions.json"));
require(path.join(root, "docs", "generated", "wikifn_engine.cjs"));

const nameTable = JSON.stringify(catalog.names || {});

// The prelude is written alongside the listing so the two can be loaded
// together in a Scheme and the runnable functions actually called.
const { PRELUDE, SHIMS, HAS_FILTER_SHIM, preludeNames } = await import("./export-scheme.js");

const CLASSIC = [
  ["identity", "Z801"], ["if", "Z802"], ["cons", "Z810"], ["car", "Z811"],
  ["cdr", "Z812"], ["null?", "Z813"], ["fst", "Z821"], ["snd", "Z822"],
  ["string=?", "Z866"], ["filter", "Z872"], ["map", "Z873"], ["fold", "Z876"],
  ["and", "Z10174"], ["or", "Z10184"], ["not", "Z10216"], ["length", "Z12681"],
  ["+", "Z13521"], ["=", "Z13522"], ["*", "Z13539"], ["add1", "Z13578"],
  ["max", "Z13630"], ["min", "Z13633"], ["expt", "Z13647"], [">", "Z13676"],
  [">=", "Z13682"], ["<", "Z13689"], ["<=", "Z13695"]
];

const lines = [
  ";; Wikifunctions compositions as s-expressions.",
  ";; Generated by scripts/export-all-scheme.js; do not edit.",
  ";;",
  ";; Rendered by Wikifn.Print, the same checked F* module the evaluator uses,",
  ";; so a printed body cannot disagree with the body that runs.",
  ";;",
  ";; Most names are the ZID followed by the English label, so the text reads as",
  ";; language while mapping back to a plain identifier by taking the first",
  ";; token. Labels come from the pinned snapshot and are therefore stable.",
  ";;",
  ";; This file is a reference listing, not a runnable program: the primitives",
  ";; it calls are implemented in F*, not here, and not every function's callees",
  ";; are present. For something you can run, export one function with its",
  ";; dependencies and a prelude:",
  ";;",
  ";;   node scripts/export-scheme.js Z10627 --call '\"Hello!\"' --out rot13.scm",
  ";;   chez --script rot13.scm",
  ";;",
  ";; Primitives that LISP already named keep the classical name. In value",
  ";; position, and/or/if are wrapped in a lambda, because they are syntax in",
  ";; Scheme rather than procedures. The mapping back to Wikifunctions:",
  ";;",
  ...CLASSIC.map(([name, zid]) => `;;   ${name.padEnd(12)} ${zid}`),
  ";;",
  ""
];

let rendered = 0;
let failed = 0;
for (const entry of catalog.functions) {
  const result = JSON.parse(
    globalThis.wikifnEngineSource(entry.zid, String(entry.arity), nameTable));
  if (!result.ok) { failed += 1; continue; }
  rendered += 1;
  lines.push(`;; ${entry.zid} ${entry.label}${entry.runnable ? "" : "  [reaches an unimplemented function]"}`);
  lines.push(result.source);
  lines.push("");
}

const preludeLines = [
  ";; Prelude for wikifn.scm.",
  ";; Generated by scripts/export-all-scheme.js; do not edit.",
  ";;",
  ";; The Wikifunctions primitives have no native Scheme equivalent, so they are",
  ";; implemented here. These are the Scheme counterparts of the F* primitive",
  ";; kernel: the same intent, written twice, which is worth knowing when",
  ";; comparing results.",
  ";;",
  ";; Load this first, then wikifn.scm:",
  ";;",
  ";;   (load \"wikifn-prelude.scm\")",
  ";;   (load \"wikifn.scm\")",
  ";;   (Z10627_rot13_latin_alphabet \"Hello!\")",
  "",
  SHIMS,
  HAS_FILTER_SHIM,
  ""
];
for (const [name, zid] of preludeNames) {
  const build = PRELUDE.get(zid);
  if (build) preludeLines.push(build(name), "");
}
await writeFile(
  path.join(root, "docs", "generated", "wikifn-prelude.scm"),
  preludeLines.join("\n"),
  "utf8"
);

const out = path.join(root, "docs", "generated", "wikifn.scm");
await writeFile(out, lines.join("\n"), "utf8");
console.log(`${rendered} definitions written${failed ? `, ${failed} could not be rendered` : ""}`);
console.log(out);
console.log(path.join(root, "docs", "generated", "wikifn-prelude.scm"));
