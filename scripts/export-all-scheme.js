#!/usr/bin/env node
// Write every generated composition to docs/generated/wikifn.scm, rendered by
// Wikifn.Print.
//
// This runs after the engine is built rather than during generation, because
// the printer is part of the engine. That ordering is the point: there is one
// renderer, it is checked F*, and a printed body cannot disagree with the body
// that runs.
//
//   node scripts/export-all-scheme.js

import { createRequire } from "node:module";
import { copyFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const catalog = require(path.join(root, "docs", "generated", "functions.json"));
require(path.join(root, "docs", "generated", "wikifn_engine.cjs"));

const nameTable = JSON.stringify(catalog.names || {});

// The prelude is written alongside the listing so the two can be loaded
// together in a Scheme and the runnable functions actually called.
const { PRELUDE, SHIMS, HAS_FILTER_SHIM, preludeNames } = await import("./export-scheme.js");

const CLASSIC = [
  ["identity", "Z801"], ["if", "Z802"], ["cons", "Z810"], ["car", "Z811"],
  ["cdr", "Z812"], ["null?", "Z813"], ["fst", "Z821"], ["snd", "Z822"],
  ["string=?", "Z866"], ["filter", "Z872"], ["map", "Z873"], ["fold", "Z876"],
  ["bool-and", "Z10174"], ["bool-or", "Z10184"], ["not", "Z10216"], ["length", "Z12681"],
  ["+", "Z13521"], ["=", "Z13522"], ["*", "Z13539"], ["add1", "Z13578"],
  ["max", "Z13630"], ["min", "Z13633"], ["expt", "Z13647"], [">", "Z13676"],
  [">=", "Z13682"], ["<", "Z13689"], ["<=", "Z13695"]
];

const lines = [
  ";; Wikifunctions compositions as s-expressions.",
  ";; Generated by scripts/export-all-scheme.js; do not edit.",
  ";;",
  ";; Rendered by Wikifn.Print, the same checked F* module the evaluator uses,",
  ";; so a printed body cannot disagree with the body that runs.",
  ";;",
  ";; Most names are the ZID followed by the English label, so the text reads as",
  ";; language while mapping back to a plain identifier by taking the first",
  ";; token. Labels come from the pinned snapshot and are therefore stable.",
  ";;",
  ";; Only the ZID is the identity. Everything after the underscore is a hint",
  ";; for whoever is reading, and each definition is also bound to its bare ZID,",
  ";; so (Z10627 \"Hello\") and (Z10627_rot13_latin_alphabet \"Hello\") are the",
  ";; same call. To write a hint of your own - shorter, longer, in another",
  ";; language - load wikifn-hints.scm and wrap the code in (wikifn ...), which",
  ";; rewrites every Znnnn_... name down to Znnnn before it is compiled.",
  ";;",
  ";; Each definition carries its declared argument and return types as a",
  ";; comment. Those are read from the pinned Z8 and are not checked by the",
  ";; evaluator; they say what the function was declared to want.",
  ";;",
  ";; This file is a reference listing, not a runnable program: the primitives",
  ";; it calls are implemented in F*, not here, and not every function's callees",
  ";; are present. For something you can run, export one function with its",
  ";; dependencies and a prelude:",
  ";;",
  ";;   node scripts/export-scheme.js Z10627 --call '\"Hello!\"' --out rot13.scm",
  ";;   chez --script rot13.scm",
  ";;",
  ";; Primitives that LISP already named keep the classical name. In value",
  ";; position, and/or/if are wrapped in a lambda, because they are syntax in",
  ";; Scheme rather than procedures. The mapping back to Wikifunctions:",
  ";;",
  ...CLASSIC.map(([name, zid]) => `;;   ${name.padEnd(12)} ${zid}`),
  ";;",
  ""
];

// Declared types, printed as a comment above each definition.
//
// Wikifunctions is typed and this listing was not saying so, which left no way
// to see that an argument wants a pair rather than a string until the evaluator
// refused it. These come from the pinned Z8 and are documentation only: the
// engine does not check them, so a wrong one is a wrong comment, not a wrong
// answer.
function signatureComment(entry) {
  const keys = entry.argumentKeys || [];
  const types = entry.argumentTypes || [];
  const args = keys.length
    ? keys.map((key, index) => `${key}: ${types[index] ?? "?"}`).join(", ")
    : "no arguments";
  return `${args} -> ${entry.returnType ?? "?"}   [declared, not checked]`;
}

let rendered = 0;
let failed = 0;
const unrenderable = [];
for (const entry of catalog.functions) {
  // The printer recurses over the body, so a body deep enough exhausts the
  // JavaScript stack before it exhausts anything in F*. That is a limit of the
  // host, not of the composition, so it is counted and named rather than
  // allowed to end the run and lose the other few thousand listings.
  let result;
  try {
    result = JSON.parse(
      globalThis.wikifnEngineSource(entry.zid, String(entry.arity), nameTable));
  } catch (error) {
    failed += 1;
    unrenderable.push(`${entry.zid} ${entry.label}: ${error.message}`);
    continue;
  }
  if (!result.ok) { failed += 1; unrenderable.push(`${entry.zid} ${entry.label}: ${result.message ?? "not rendered"}`); continue; }
  rendered += 1;
  const notes = [];
  if (!entry.runnable) notes.push("reaches an unimplemented function");
  if (entry.mutuallyRecursive) notes.push("mutually recursive: may not terminate");
  lines.push(`;; ${entry.zid} ${entry.label}${notes.length ? "  [" + notes.join("; ") + "]" : ""}`);
  lines.push(`;;   ${signatureComment(entry)}`);
  lines.push(result.source);
  // The ZID alone is the identity; everything after the underscore is a hint
  // for the reader. Binding the bare ZID too means a caller can write either,
  // and a program written with one spelling of the hint keeps working when the
  // label changes.
  lines.push(`(define ${entry.zid} ${entry.name})`);
  lines.push("");
}

const preludeLines = [
  ";; Prelude for wikifn.scm.",
  ";; Generated by scripts/export-all-scheme.js; do not edit.",
  ";;",
  ";; The Wikifunctions primitives have no native Scheme equivalent, so they are",
  ";; implemented here. These are the Scheme counterparts of the F* primitive",
  ";; kernel: the same intent, written twice, which is worth knowing when",
  ";; comparing results.",
  ";;",
  ";; Load this first, then wikifn.scm:",
  ";;",
  ";;   (load \"wikifn-prelude.scm\")",
  ";;   (load \"wikifn.scm\")",
  ";;   (Z10627_rot13_latin_alphabet \"Hello!\")",
  "",
  SHIMS,
  HAS_FILTER_SHIM,
  ""
];
for (const [name, zid] of preludeNames) {
  const build = PRELUDE.get(zid);
  if (build) preludeLines.push(build(name), "");
}

// Every primitive reachable by its ZID as well as by its name.
//
// Without this, the primitives were the one part of the language you could not
// address the way Wikifunctions addresses everything else. A caller who knows
// Z810 had to know that it is spelled cons here, and the hint macro in
// wikifn-hints.scm could not help either, because it rewrites Znnnn_... down to
// Znnnn and there was no Znnnn to rewrite to.
preludeLines.push(
  ";; Primitives by ZID.",
  ";;",
  ";; The classical name is for reading and the ZID is the identity, so both",
  ";; work: (cons 1 (list)) and (Z810 1 (list)) are the same call.",
  ""
);
const aliased = new Set();
for (const [name, zid] of [...CLASSIC, ...[...preludeNames].map(([n, z]) => [n, z])]) {
  if (aliased.has(zid)) continue;
  aliased.add(zid);
  // Z802 and Z13846 choose a branch, and in Scheme if is syntax rather than a
  // procedure. Binding them with define would evaluate both branches, and 230
  // of the 288 directly self-recursive compositions in the corpus guard their
  // recursive branch with Z802, so all of them would diverge. A macro keeps the
  // branch lazy and the ZID callable.
  if (zid === "Z802" || zid === "Z13846") {
    preludeLines.push(
      `(define-syntax ${zid}`,
      "  (syntax-rules ()",
      "    ((_ condition consequent alternative)",
      "     (if condition consequent alternative))))",
      ""
    );
    continue;
  }
  preludeLines.push(`(define ${zid} ${name})`);
}
preludeLines.push("");
await writeFile(
  path.join(root, "docs", "generated", "wikifn-prelude.scm"),
  preludeLines.join("\n"),
  "utf8"
);

const out = path.join(root, "docs", "generated", "wikifn.scm");
await writeFile(out, lines.join("\n"), "utf8");
console.log(`${rendered} definitions written${failed ? `, ${failed} could not be rendered` : ""}`);
for (const line of unrenderable.slice(0, 20)) console.log(`  ${line}`);
console.log(out);
// One file that can be loaded from a single URL: prelude first, then every
// definition. This is what a Scheme editor wants.
const bundle = [
  ";; Wikifunctions in Scheme: prelude and all generated definitions in one file.",
  ";; Generated by scripts/export-all-scheme.js; do not edit.",
  ";;",
  ";; Load this one file, then call a function by name, for example:",
  ";;",
  ";;   (Z10627_rot13_latin_alphabet \"Hello, Wikifunctions!\")",
  ";;   (Z22294_devanagari_numerals_to_arabic_numerals \"१२३४५\")",
  ";;",
  ";; Only the ZID identifies the function; the rest of the name is a hint for",
  ";; the reader. Each definition is bound to its bare ZID as well, so",
  ";; (Z10627 \"Hello\") is the same call. Load wikifn-hints.scm and wrap code in",
  ";; (wikifn ...) to use a hint of your own instead.",
  ";;",
  ";; Each definition carries its declared argument and return types as a",
  ";; comment. They come from the pinned Z8 and the evaluator does not check",
  ";; them.",
  ";;",
  ";; Not every definition here can run. Some reach functions nobody has",
  ";; implemented. Others are defined in terms of each other with no base case,",
  ";; which is true as an equation and unproductive as a definition; Scheme has",
  ";; no depth guard, so those overflow the stack rather than returning. Both",
  ";; are marked in the comment above the definition.",
  "",
  ...preludeLines.slice(preludeLines.indexOf("")),
  "",
  ...lines.slice(lines.indexOf(""))
].join("\n");
const bundlePath = path.join(root, "docs", "generated", "wikifn-bundle.scm");
await writeFile(bundlePath, bundle, "utf8");

// Authored, not generated, so it is copied rather than built: it is the same
// file whatever the corpus says.
const hintsPath = path.join(root, "docs", "generated", "wikifn-hints.scm");
await copyFile(path.join(root, "scripts", "wikifn-hints.scm"), hintsPath);

console.log(path.join(root, "docs", "generated", "wikifn-prelude.scm"));
console.log(bundlePath);
console.log(hintsPath);
